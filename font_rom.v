// 8x8 font for the hex digits 0 to F
//
// digit : which hex digit (0 to 15)
// row   : which row of the digit (0 = top, row 7 is always blank)
// bits  : the 8 pixels of that row, bits[7] = leftmost pixel, 1 = on
// look at my goodnotes lol

